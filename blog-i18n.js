export function matchLocale(requested) {
  return Object.keys(messages).find((locale) => locale.toLowerCase() === requested.toLowerCase())
    ?? { es: "es-419", fr: "fr-FR", pt: "pt-BR" }[requested.split("-")[0].toLowerCase()]
    ?? "en-US";
}
